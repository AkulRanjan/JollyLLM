"""Build the Kaggle CPU notebooks for the score-improvement plan from their `# %%` cell files.

    python scripts/build_jolly_notebooks.py            # writes kaggle-notebooks/<slug>/<slug>.ipynb + kernel-metadata.json

Each notebook folder holds `cells.py` (readable cells, one `# %%` marker per cell, `# %% [markdown]` for text) and
the generated notebook. A hidden first cell embeds the `legal_graph` package so the notebook runs on Kaggle or
locally (`JOLLY_RECORDS` / `JOLLY_OUT` environment variables replace the Kaggle paths).
"""

from __future__ import annotations

import base64
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from build_kaggle_notebook import build_bundle, code, markdown  # noqa: E402
from kaggle_run import kernel_metadata  # noqa: E402

NOTEBOOKS = ROOT / "kaggle-notebooks"
OWNER = "vanshag08"
EXTRACT = "jolly-aws-extract"
PROBES = "jolly-phase1-probes"
NEURAL = "jolly-phase3-neural"
FINAL = "jolly-phase5-test"
ROUND2 = "jolly-round2-probes"
REGISTRY = ROOT / "configs/sources/aws-sc-source.json"


def pinned_archive_hashes() -> dict[str, str]:
    notes = json.loads(REGISTRY.read_text(encoding="utf-8"))["sources"][0]["notes"]
    return dict(re.findall(r"((?:data|metadata)/tar/year=\d+/(?:english/english|metadata)\.tar) sha256 ([0-9a-f]{64})", notes))


def preamble_cell(extra: str = "") -> dict[str, object]:
    bundle = build_bundle(sorted((ROOT / "src/legal_graph").glob("*.py")))
    encoded = base64.b64encode(bundle).decode("ascii")
    wrapped = "\n".join(encoded[start : start + 120] for start in range(0, len(encoded), 120))
    source = (
        "# Embedded legal_graph package, generated by scripts/build_jolly_notebooks.py. Regenerate it; don't edit by hand.\n"
        f"BUNDLE_SHA256 = {hashlib.sha256(bundle).hexdigest()!r}\n"
        f"{extra}"
        f'BUNDLE_B64 = """\n{wrapped}\n"""\n'
        "import base64, hashlib, io, os, sys, tarfile, tempfile\n"
        "from pathlib import Path\n"
        "ON_KAGGLE = Path('/kaggle/working').is_dir()\n"
        "LOCAL_OUT = os.environ.get('JOLLY_OUT', 'jolly-out')\n"
        "payload = base64.b64decode(''.join(BUNDLE_B64.split()))\n"
        "assert hashlib.sha256(payload).hexdigest() == BUNDLE_SHA256, 'bundle corrupted'\n"
        "WORK = Path(tempfile.gettempdir()) / 'jolly-work'\n"
        "WORK.mkdir(parents=True, exist_ok=True)\n"
        "with tarfile.open(fileobj=io.BytesIO(payload), mode='r:gz') as archive:\n"
        "    try:\n"
        "        archive.extractall(WORK, filter='data')\n"
        "    except TypeError:\n"
        "        archive.extractall(WORK)\n"
        "sys.path.insert(0, str(WORK / 'src'))\n"
        "print('legal_graph bundle', BUNDLE_SHA256[:16], 'ON_KAGGLE =', ON_KAGGLE)\n"
    )
    return code(source, hidden=True)


def parse_cells(path: Path) -> list[dict[str, object]]:
    cells: list[dict[str, object]] = []
    kind, buffer = None, []

    def flush() -> None:
        if kind is None:
            return
        body = "\n".join(buffer).strip("\n")
        if kind == "markdown":
            cells.append(markdown("\n".join(line[2:] if line.startswith("# ") else line.lstrip("#") for line in body.splitlines())))
        elif body.strip():
            cells.append(code(body))

    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# %%"):
            flush()
            kind, buffer = ("markdown" if "[markdown]" in line else "code"), []
        else:
            buffer.append(line)
    flush()
    return cells


def notebook(cells: list[dict[str, object]], *, internet: bool, gpu: bool = False) -> dict[str, object]:
    for index, cell in enumerate(cells):
        cell["id"] = f"cell-{index:02d}"
    return {
        "cells": cells,
        "metadata": {
            "kaggle": {"accelerator": "nvidiaTeslaT4" if gpu else "none", "dataSources": [], "isGpuEnabled": gpu,
                       "isInternetEnabled": internet, "language": "python", "sourceType": "notebook"},
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def write(slug: str, extra: str, *, internet: bool, kernel_sources: list[str], gpu: bool = False,
          cells_from: str | None = None) -> Path:
    folder = NOTEBOOKS / slug
    folder.mkdir(parents=True, exist_ok=True)
    cells = [preamble_cell(extra)] + parse_cells(NOTEBOOKS / (cells_from or slug) / "cells.py")
    path = folder / f"{slug}.ipynb"
    path.write_text(json.dumps(notebook(cells, internet=internet, gpu=gpu), indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    metadata = kernel_metadata(f"{OWNER}/{slug}", slug, path.name, gpu=gpu, internet=internet, kernel_sources=kernel_sources)
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"{path.relative_to(ROOT)}: {path.stat().st_size:,} bytes, {len(cells)} cells")
    return folder


def main() -> None:
    write(EXTRACT, f"PINNED_SHA256 = {json.dumps(pinned_archive_hashes(), indent=4)}\n", internet=True, kernel_sources=[])
    # fresh test years for round 2; same cells, labels never printed
    write(EXTRACT + "-2019", f"PINNED_SHA256 = {{}}\nJOLLY_YEARS = [2019, 2020]\n", internet=True, kernel_sources=[],
          cells_from=EXTRACT)
    write(PROBES, "", internet=False, kernel_sources=[f"{OWNER}/{EXTRACT}"])
    write(NEURAL, "", internet=True, kernel_sources=[f"{OWNER}/{EXTRACT}"], gpu=True)
    # same cells on a tiny sample in a free CPU session, to catch code errors before the GPU run
    write(NEURAL + "-smoke", "import os\nos.environ['JOLLY_SMOKE'] = '1'\n", internet=True,
          kernel_sources=[f"{OWNER}/{EXTRACT}"], cells_from=NEURAL)
    write(FINAL, "", internet=False, kernel_sources=[f"{OWNER}/{EXTRACT}"])
    write(FINAL + "-smoke", "import os\nos.environ['JOLLY_SMOKE'] = '1'\n", internet=False,
          kernel_sources=[f"{OWNER}/{EXTRACT}"], cells_from=FINAL)
    write(ROUND2, "", internet=False, kernel_sources=[f"{OWNER}/{EXTRACT}"])


if __name__ == "__main__":
    main()
